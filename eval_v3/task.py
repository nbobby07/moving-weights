def check(condition, message):
    if not condition:
        raise ValueError(message)


def tree_hash(folder, python_only=False):
    h = hashlib.sha256()
    for path in sorted(folder.rglob("*"), key=lambda p:p.relative_to(folder).as_posix()):
        check(not path.is_symlink(), "unexpected source symlink")
        if path.is_file() and (not python_only or path.suffix == ".py"):
            h.update(path.relative_to(folder).as_posix().encode()+b"\0")
            h.update(hashlib.sha256(path.read_bytes()).digest())
    return h.hexdigest()


def rng(seed):
    return torch.Generator().manual_seed(seed)


class Transformer:
    def __init__(self, device, smoke=False):
        self.device = device
        self.width, self.layers, self.heads = (32,2,4) if smoke else (512,4,8)
        d = self.width
        self.shapes = [(40,d),(6,d)] + [(3*d,d),(d,d),(3*d,d),(d,3*d)]*self.layers + [(16,d)]
        self.sizes = [math.prod(s) for s in self.shapes]
        self.n = sum(self.sizes)
        self.mask = torch.ones(6,6,device=device,dtype=torch.bool).triu(1)

    def initial(self, seed):
        r = rng(seed)
        parts = []
        for i,shape in enumerate(self.shapes):
            std = 0.18 if i<2 else (0.001 if i==len(self.shapes)-1 else 0.45/math.sqrt(shape[1]))
            x = torch.randn(shape,generator=r)*std
            parts.append((x.mul(2**20).round().mul(2**-20).add(0.0)).flatten())
        return torch.cat(parts).to(self.device)

    def parameters(self,q,grad=False):
        return [x.view(s).detach().requires_grad_(grad) for x,s in zip(q.split(self.sizes),self.shapes)]

    def logits(self, weights, batch):
        tokens, slot, _ = batch
        d = self.width
        # One-hot projection avoids a duplicate-token scatter in the embedding backward pass.
        x = F.one_hot(tokens,40).float() @ weights[0] + weights[1]
        n,t = tokens.shape
        for i in range(self.layers):
            wqkv,wo,wup,wdown = weights[2+4*i:6+4*i]
            z = F.layer_norm(x,(d,))
            q,k,v = F.linear(z,wqkv).reshape(n,t,3,self.heads,d//self.heads).permute(2,0,3,1,4).unbind(0)
            att = ((q@k.transpose(-1,-2))/math.sqrt(d//self.heads)).masked_fill(self.mask,-torch.inf).softmax(-1)
            x = x+F.linear((att@v).transpose(1,2).reshape(n,t,d),wo)
            x = x+F.linear(F.gelu(F.linear(F.layer_norm(x,(d,)),wup)),wdown)
        scores = F.linear(F.layer_norm(x[:,-1],(d,)),weights[-1]).view(n,8,2)
        return scores[torch.arange(n,device=x.device),slot]

    def grad(self,q,batch):
        weights=self.parameters(q,True)
        loss=F.cross_entropy(self.logits(weights,batch),batch[2])
        grads=torch.autograd.grad(loss,weights)
        return torch.cat([g.reshape(-1) for g in grads])

    def observe(self,q,batch):
        with torch.no_grad():
            logits=self.logits(self.parameters(q),batch)
            lp=logits.log_softmax(-1)
            return torch.stack((F.nll_loss(lp,batch[2]),-(lp.exp()*lp).sum(-1).mean(),
                                (logits.argmax(-1)!=batch[2]).float().mean())).tolist()


class Problem:
    def __init__(self, seed, depth, device):
        self.seed,self.depth,self.device=seed,depth,device
        self.base=torch.randint(2,(depth,),generator=rng(seed*101+1)).tolist()
        self.codes=[tuple([0]*depth)]+[tuple(int(i==j) for i in range(depth)) for j in reversed(range(depth))]
        self.answers=[tuple(v^u for v,u in zip(c,self.base)) for c in self.codes]
        # Read-only external corpus, generated by stable ID, shared by all methods.
        self.bank={}
        for level in range(depth):
            for bit in (0,1):
                for k in range(K+1):
                    eid=(level*2+bit)*(K+1)+k
                    # Same features on both hypotheses; clean conditional targets differ.
                    self.bank[eid]=self.batch(level,bit,k,4)
        tests=[self.batch(i,0,97,8) for i in range(depth)]
        self.challenge=tuple(torch.cat(xs) for xs in zip(*tests))

    def batch(self,level,bit,nonce,n):
        gen=rng(self.seed*10000+level*100+nonce)
        tokens=torch.randint(16,40,(n,6),generator=gen)
        tokens[:,0]=0
        tokens[:,2]=1+level
        tokens[:,-1]=1+level
        return (tokens.to(self.device),torch.full((n,),level,device=self.device),
                torch.full((n,),self.base[level]^bit,device=self.device))

    def query(self,model,q):
        # No branch ID or secret enters the model. The private verifier sees predictions only.
        with torch.no_grad():
            pred=model.logits(model.parameters(q),self.challenge).argmax(-1).view(self.depth,8)
            return pred.sum(-1).tolist()

    def private_draws(self):
        return torch.randint(self.depth+1,(128,),generator=rng(self.seed*100003+self.depth)).tolist()

    def verifier(self,ones,secret):
        return all((v if target else 8-v)>=7 for v,target in zip(ones,self.answers[secret]))
